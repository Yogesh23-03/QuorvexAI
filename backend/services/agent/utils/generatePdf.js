import PDFDocument from "pdfkit";

const COLORS = {
  heading: "#111827",
  body: "#374151",
  muted: "#9CA3AF",
  subtitle: "#6B7280",
  accent: "#4F46E5",
};

export function buildPdf(data) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "QuorvexAI",
        Title: data?.title || "QuorvexAI document",
        Creator: "QuorvexAI",
      },
    });

    const chunks = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc
      .fontSize(26)
      .fillColor(COLORS.heading)
      .text(data?.title || "Document", { align: "center" });

    if (data?.subtitle) {
      doc.moveDown(0.5);
      doc.fontSize(12).fillColor(COLORS.subtitle).text(data.subtitle, { align: "center" });
    }

    doc.moveDown(1.5);

    (data?.sections || []).forEach((section) => {
      if (section?.heading) {
        doc.fontSize(16).fillColor(COLORS.accent).text(section.heading);
        doc.moveDown(0.4);
      }
      (section?.points || []).forEach((point) => {
        doc.fontSize(11).fillColor(COLORS.body).text(`•  ${point}`, { lineGap: 4 });
      });
      doc.moveDown();
    });

    doc.moveDown(1.5);
    doc.fontSize(9).fillColor(COLORS.muted).text("Generated by QuorvexAI", { align: "center" });

    doc.end();
  });
}

export const generatePdf = buildPdf;
export default buildPdf;
